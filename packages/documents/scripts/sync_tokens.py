"""Copy Verdant's colour and font tokens into a Python module for documents.

The Python twin of grove-email's sync-tokens.mjs. It reads @servantium/verdant's
tokens.css, the SAME file every website, the portal and every email read, and writes
src/servantium_documents/tokens.py. Change a colour in Verdant, run `npm run tokens`
(or `python scripts/sync_tokens.py`), rebuild, and the decks follow. Nothing in this
package defines a brand colour of its own, except the short list of DOCUMENT
EXTENSIONS below, each of which says why Verdant does not have it yet.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
TOKENS_CSS = PKG.parent / 'verdant' / 'tokens.css'
OUT = PKG / 'src' / 'servantium_documents' / 'tokens.py'

# Documents need a few values the web does not. Each one is a candidate to move into
# Verdant; until it does, it lives here, loudly, rather than as a literal in a builder.
DOCUMENT_EXTENSIONS = {
    # Long-form body text on slides and pages. Pure ink (#0D0D0D) is too heavy at
    # 11-16pt across a whole page; every deck to date has used this softer value.
    'color-ink-soft': '#34404D',
    # Text on deep-forest grounds (covers, closing slides, dark cards). The web puts
    # white on forest; slides need a readable second tier below the white title.
    'color-on-forest': '#CBEADA',
    'color-on-forest-muted': '#8FC4AB',
    # The spreadsheet modeling convention: blue input, green cross-sheet link, amber
    # warning text. Finance readers know it without a legend, so it overrides the
    # palette on purpose. Only workbooks use these.
    'color-model-input': '#1D4ED8',
    'color-model-input-fill': '#EEF3FF',
    'color-model-link': '#0B7A3E',
    'color-model-warning': '#B45309',
}


def parse(css: str):
    colors, fonts = {}, {}
    for name, raw in re.findall(r'--(color-[a-z0-9-]+)\s*:\s*([^;]+);', css):
        value = raw.strip()
        # Literal hex only; rgba() overlays have no meaning in a document.
        if re.fullmatch(r'#[0-9a-fA-F]{6}', value) and name not in colors:
            colors[name] = value.upper()
    for name, raw in re.findall(r'--(font-[a-z0-9-]+)\s*:\s*([^;]+);', css):
        first = raw.split(',')[0].strip().strip('\'"')
        if name not in fonts:
            fonts[name] = first
    return colors, fonts


def main():
    css = TOKENS_CSS.read_text()
    colors, fonts = parse(css)
    for k, v in DOCUMENT_EXTENSIONS.items():
        if k in colors:
            raise SystemExit(f'{k} now exists in Verdant ({colors[k]}); delete it from DOCUMENT_EXTENSIONS')
        colors[k] = v.upper()
    lines = [
        '"""GENERATED by scripts/sync_tokens.py from packages/verdant/tokens.css. Do not edit.',
        '',
        'Change the token in Verdant and run `npm run tokens`. Document-only values are',
        'marked in the generator, with the reason Verdant does not carry them yet.',
        '"""',
        '',
        'COLORS = {',
        *[f'    {k!r}: {v!r},' for k, v in sorted(colors.items())],
        '}',
        '',
        'FONTS = {',
        *[f'    {k!r}: {v!r},' for k, v in sorted(fonts.items())],
        '}',
        '',
        f'DOCUMENT_EXTENSIONS = {sorted(DOCUMENT_EXTENSIONS)!r}',
        '',
    ]
    OUT.write_text('\n'.join(lines))
    print(f'synced {len(colors)} colours and {len(fonts)} fonts from verdant -> {OUT.relative_to(PKG)}')


if __name__ == '__main__':
    main()
