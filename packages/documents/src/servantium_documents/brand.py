"""One source of brand truth for the three Office templates.

Colours and fonts come from kit, which binds them to Verdant tokens generated by
scripts/sync_tokens.py. Nothing here restates a hex value.

The theme writer is shared because .pptx, .docx and .xlsx all carry the same
DrawingML theme part. Writing the brand INTO the theme (not just onto shapes) is
what makes the colour picker show Servantium colours and makes "new slide" or a
new heading inherit the right fonts, in Office and on import to Google.
"""
from pathlib import Path

from . import kit as K

ASSETS = K.ASSETS
DIST = K.DIST                      # dist/ for Servantium, dist/<brand>/ for every other brand
DIST.mkdir(parents=True, exist_ok=True)
LOGO_ON_LIGHT, LOGO_ON_DARK, MARK_ON_DARK = K.LOGO_ON_LIGHT, K.LOGO_ON_DARK, K.MARK_ON_DARK


def hexof(rgb):
    return f'{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}'


# Theme slots. Office and Google both assign chart series colours from accent1..6
# in order, so the order here IS the default chart palette.
THEME_COLORS = [
    ('dk1', hexof(K.INK)), ('lt1', hexof(K.WHITE)),
    ('dk2', hexof(K.FOREST)), ('lt2', hexof(K.MINT)),
    ('accent1', hexof(K.GREEN)), ('accent2', hexof(K.FOREST)),
    ('accent3', hexof(K.SLATE)), ('accent4', hexof(K.TEAL)),
    ('accent5', hexof(K.ACCENT_3)), ('accent6', hexof(K.ACCENT_4)),
    ('hlink', hexof(K.GREEN_600)), ('folHlink', hexof(K.INK_MUTED)),
]

# Fonts. Both are on Google Fonts, so Slides/Docs/Sheets render them natively.
# Microsoft does NOT ship them, so on a customer's PC Office substitutes. It picks
# the substitute from pitchFamily (and panose when present). Playfair ships with an
# all-zero panose, so without pitchFamily=0x12 (roman, variable pitch) Office has
# no signal it is a serif at all. Source Sans 3's real panose is kept from the file.
def _face(role, family, panose, pitch):
    f = K.ACTIVE.fonts.get(role, {})
    return dict(typeface=family, panose=str(f.get('panose', panose)), pitchFamily=str(f.get('pitch', pitch)), charset='0')


DISPLAY = _face('display', K.DISPLAY, '02000503000000020004', '18')
BODY = _face('body', K.UI, '020B0303030403020204', '34')


def brand_theme_xml(base: bytes, name=None) -> bytes:
    """Rewrite colour and font schemes in a theme1.xml, keeping everything else."""
    from lxml import etree
    A = 'http://schemas.openxmlformats.org/drawingml/2006/main'
    q = lambda t: f'{{{A}}}{t}'
    name = name or K.BRAND_SHORT
    root = etree.fromstring(base)
    root.set('name', name)
    te = root.find(q('themeElements'))

    cs = te.find(q('clrScheme'))
    cs.set('name', name)
    for slot, hx in THEME_COLORS:
        el = cs.find(q(slot))
        for c in list(el):
            el.remove(c)
        etree.SubElement(el, q('srgbClr')).set('val', hx)

    fs = te.find(q('fontScheme'))
    fs.set('name', name)
    for which, spec in (('majorFont', DISPLAY), ('minorFont', BODY)):
        grp = fs.find(q(which))
        latin = grp.find(q('latin'))
        for k, v in spec.items():
            latin.set(k, v)
    return etree.tostring(root, xml_declaration=True, encoding='UTF-8', standalone=True)


def apply_theme_to_package(package):
    """Rewrite every theme part in a python-pptx / python-docx package."""
    for part in package.iter_parts():
        if 'theme' in str(part.partname):
            part._blob = brand_theme_xml(part.blob)
